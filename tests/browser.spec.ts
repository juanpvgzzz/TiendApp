import { test, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { randomBytes, randomUUID } from 'node:crypto';
import { createClient } from '@supabase/supabase-js';

test.use({ actionTimeout: 10_000 });
test('administrador y cliente completan una cuenta real', async ({ browser }) => {
  test.setTimeout(180_000);
  const status = JSON.parse(execFileSync('npx', ['--no-install','supabase','status','--output','json'], { encoding:'utf8' }));
  expect(status.API_URL).toBe('http://127.0.0.1:54321');
  expect(status.DB_URL).toMatch(/@127\.0\.0\.1:54322\//);
  const root = createClient(status.API_URL,status.SERVICE_ROLE_KEY,{auth:{persistSession:false}});
  const email=`browser-${randomUUID()}@tiendapp.test`;
  const password=randomBytes(24).toString('base64url');
  const created=await root.auth.admin.createUser({email,password,email_confirm:true});
  if (created.error || !created.data.user) throw created.error ?? new Error('No se creó el usuario de prueba.');
  const adminId=created.data.user.id;
  expect(adminId).toMatch(/^[0-9a-f-]{36}$/);
  execFileSync('docker',['exec','-i','supabase_db_tiendapp','psql','-U','postgres','-d','postgres','-v','ON_ERROR_STOP=1','-c',
    `insert into public.staff(user_id,role,display_name) values ('${adminId}','admin','Encargado de prueba')`],{stdio:'pipe'});

  const admin=await browser.newContext({viewport:{width:390,height:844}});
  const customer=await browser.newContext({viewport:{width:390,height:844}});
  const outsider=await browser.newContext({viewport:{width:390,height:844}});
  const a=await admin.newPage();
  const c=await customer.newPage();
  const o=await outsider.newPage();
  const errors:string[]=[];
  a.on('pageerror',(error)=>errors.push(`admin: ${error.message}`));
  c.on('pageerror',(error)=>errors.push(`cliente: ${error.message}`));
  a.on('console',(message)=>{if(message.type()==='error') errors.push(`admin consola: ${message.text()}`);});
  c.on('console',(message)=>{if(message.type()==='error') errors.push(`cliente consola: ${message.text()}`);});
  a.on('dialog',(dialog)=>void dialog.accept());
  c.on('dialog',(dialog)=>void dialog.accept());
  const clientName=`Juancho ${randomUUID().slice(0,6)}`;
  const categoryName=`Bebidas ${randomUUID().slice(0,6)}`;
  const productName=`Cerveza ${randomUUID().slice(0,6)}`;

  const outsiderEmail=`outsider-${randomUUID()}@tiendapp.test`;
  const outsiderUser=await root.auth.admin.createUser({email:outsiderEmail,password,email_confirm:true});
  expect(outsiderUser.error).toBeNull();
  await o.goto('http://127.0.0.1:5173/admin/login');
  await o.getByRole('textbox',{name:'Correo electrónico'}).fill(outsiderEmail);
  await o.getByLabel('Contraseña').fill('wrong-password');
  await o.getByRole('button',{name:'Ingresar'}).click();
  await expect(o.getByText('Correo o contraseña incorrectos.')).toBeVisible();
  await o.getByLabel('Contraseña').fill(password);
  await o.getByRole('button',{name:'Ingresar'}).click();
  await expect(o.getByText('Tu usuario no tiene acceso al personal.')).toBeVisible();

  await a.goto('http://127.0.0.1:5173/admin');
  await expect(a).toHaveURL(/\/admin\/login$/);
  await a.getByRole('textbox',{name:'Correo electrónico'}).fill(email);
  await a.getByLabel('Contraseña').fill(password);
  await a.getByRole('button',{name:'Ingresar'}).click();
  await expect(a.getByRole('heading',{name:'Lo que necesita atención'})).toBeVisible();

  await a.goto('http://127.0.0.1:5173/admin/catalogo');
  await a.getByRole('textbox',{name:'Nombre'}).first().fill(categoryName);
  await a.getByRole('button',{name:'Guardar',exact:true}).click();
  await expect(a.getByText('Categoría guardada.')).toBeVisible();
  await a.getByRole('combobox',{name:'Categoría'}).first().selectOption({label:categoryName});
  await a.getByRole('textbox',{name:'Nombre'}).last().fill(productName);
  await a.getByLabel('Precio en COP').fill('5000');
  await a.getByRole('button',{name:'Crear producto'}).click();
  await expect(a.getByText('Producto creado.')).toBeVisible();
  await a.locator('.list-row').filter({hasText:productName}).getByRole('button',{name:'Editar'}).click();
  const fixtureImage=await a.evaluate(()=>{const canvas=document.createElement('canvas');canvas.width=32;canvas.height=32;const context=canvas.getContext('2d');if(!context)throw new Error('Canvas unavailable');context.fillStyle='#d4a017';context.fillRect(0,0,32,32);return canvas.toDataURL('image/png').split(',')[1];});
  await a.getByLabel('Seleccionar foto').setInputFiles({name:'producto.png',mimeType:'image/png',buffer:Buffer.from(fixtureImage,'base64')});
  await a.getByRole('button',{name:'Guardar fotografía'}).click();
  await expect(a.getByText('Fotografía actualizada.')).toBeVisible();
  const productRecord=await root.from('products').select('id,photo_path').eq('name',productName).single();
  expect(productRecord.error).toBeNull();
  const unprivileged=createClient(status.API_URL,status.PUBLISHABLE_KEY,{auth:{persistSession:false}});
  expect((await unprivileged.auth.signInAnonymously()).error).toBeNull();
  const deniedPhoto=await unprivileged.rpc('set_product_photo',{p_product:productRecord.data!.id,p_path:productRecord.data!.photo_path});
  expect(deniedPhoto.error).not.toBeNull();
  const deniedUpload=await unprivileged.storage.from('product-photos').upload(`${productRecord.data!.id}/${randomUUID()}.webp`,Buffer.from('not an image'),{contentType:'image/webp'});
  expect(deniedUpload.error).not.toBeNull();

  await a.goto('http://127.0.0.1:5173/admin/clientes');
  const openShift=a.getByRole('button',{name:'Abrir jornada'});
  if (await openShift.isVisible().catch(()=>false)) await openShift.click();
  await a.getByLabel('Nombre del cliente').fill(clientName);
  await a.getByRole('button',{name:'Registrar cliente'}).click();
  await expect(a.getByText('Cliente registrado. Ahora puedes abrir su cuenta.')).toBeVisible();
  await a.getByRole('button',{name:'Abrir cuenta',exact:true}).click();
  await expect(a).toHaveURL(/\/admin\/cuentas\/[0-9a-f-]+$/);
  const accountId=a.url().split('/').at(-1)!;
  await a.getByRole('button',{name:'Generar código temporal'}).click();
  const code=(await a.locator('.code').textContent())?.trim();
  expect(code).toMatch(/^[0-9A-F]{18}$/);
  await a.goto('http://127.0.0.1:5173/admin');

  await c.goto('http://127.0.0.1:5173/mi-cuenta');
  await expect(c).toHaveURL(/\/vincular$/);
  await expect(c.getByText(clientName)).toHaveCount(0);
  await c.goto('http://127.0.0.1:5173/');
  await c.getByRole('button',{name:/Acceder a mi checa/}).click();
  await expect(c).toHaveURL(/\/vincular$/);
  await c.getByLabel('Código de 18 caracteres').fill(code!);
  await c.getByRole('button',{name:'Continuar'}).click();
  await expect(c).toHaveURL(/\/mi-cuenta$/);
  await expect(c.getByRole('heading',{name:`Hola, ${clientName}`})).toBeVisible();
  const linkedUser=await root.from('account_access').select('user_id').eq('account_id',accountId).single();
  expect(linkedUser.error).toBeNull();
  const foreignChannel=unprivileged.channel(`account-access:${linkedUser.data!.user_id}`,{config:{private:true}});
  const foreignStatus=await new Promise<string>((resolve)=>foreignChannel.subscribe((state)=>{if(state==='SUBSCRIBED'||state==='CHANNEL_ERROR'||state==='TIMED_OUT')resolve(state);}));
  expect(foreignStatus).not.toBe('SUBSCRIBED');
  await unprivileged.removeChannel(foreignChannel);
  await expect(c.getByRole('button',{name:'CERVEZAS'})).toBeVisible();
  await expect(c.getByRole('button',{name:'MECATOS'})).toBeVisible();
  await c.getByRole('button',{name:'MECATOS'}).click();
  await expect(c.getByText(productName)).toHaveCount(0);
  await c.getByRole('button',{name:'CERVEZAS'}).click();
  await c.getByRole('searchbox',{name:'Buscar productos'}).fill(productName);
  const productImage=c.locator('.shop-card').filter({hasText:productName}).locator('img');
  await expect(productImage).toBeVisible();
  await productImage.scrollIntoViewIfNeeded();
  await expect.poll(()=>productImage.evaluate((image:HTMLImageElement)=>image.naturalWidth)).toBeGreaterThan(0);
  await c.screenshot({path:'/tmp/tiendapp-cliente-390.png',fullPage:true});
  await c.setViewportSize({width:320,height:844});
  await c.screenshot({path:'/tmp/tiendapp-cliente-320.png',fullPage:true});
  await c.setViewportSize({width:1024,height:844});
  await c.screenshot({path:'/tmp/tiendapp-cliente-1024.png',fullPage:true});
  await c.setViewportSize({width:390,height:844});
  await c.getByRole('navigation',{name:'Navegación móvil'}).getByRole('link',{name:'Pedidos'}).click();
  await expect(c).toHaveURL(/#mis-pedidos$/);
  await c.getByRole('navigation',{name:'Navegación móvil'}).getByRole('link',{name:'Inicio'}).click();
  await expect(c).toHaveURL(/#inicio$/);
  await c.getByRole('button',{name:`Agregar ${productName}`,exact:true}).click();
  await c.getByRole('button',{name:`Agregar una unidad de ${productName}`}).click();
  await c.getByRole('button',{name:/productos en tu pedido/}).click();
  await expect(c.getByText(`2 × ${productName}`)).toBeVisible();
  await c.getByRole('button',{name:'Confirmar pedido'}).click();
  await expect(c.getByText('Pedido enviado. La tienda te avisará cuando lo entregue.')).toBeVisible();

  const order=a.locator('#pedidos article').filter({hasText:productName});
  await expect(order).toBeVisible();
  await order.getByRole('button',{name:'Tomar pedido'}).click();
  await expect(order.getByText('En atención')).toBeVisible();
  await order.getByRole('spinbutton',{name:`Cantidad de ${productName} a entregar`}).fill('1');
  await order.getByRole('button',{name:'Entregar'}).click();
  await expect(c.locator('.metric')).toContainText('5.000');
  await order.getByRole('spinbutton',{name:`Cantidad de ${productName} a entregar`}).fill('1');
  await order.getByRole('button',{name:'Entregar'}).click();
  await expect(c.locator('.metric')).toContainText('10.000');
  await expect(c.getByText('Encargado de prueba').first()).toBeVisible();

  await c.getByRole('button',{name:'Solicitar pagar'}).click();
  await c.getByRole('button',{name:'Confirmar solicitud'}).click();
  await expect(c.getByText('Pago solicitado.',{exact:false})).toBeVisible();
  const payment=a.locator('#pagos .list-row').filter({hasText:clientName});
  await expect(payment).toBeVisible();
  await payment.getByRole('link',{name:'Revisar cobro'}).click();
  await a.getByLabel('Medio de pago').selectOption('transfer');
  await a.getByRole('button',{name:'Confirmar cobro y cerrar'}).click();
  await expect(a.getByText('Cuenta cerrada.')).toBeVisible();
  await expect(c.getByText('Pago confirmado:',{exact:false})).toBeVisible();
  await c.reload();
  await expect(c.locator('.metric')).toContainText('10.000');
  await c.goto('http://127.0.0.1:5173/');
  await c.getByRole('button',{name:/Acceder a mi checa/}).click();
  await expect(c).toHaveURL(/\/mi-cuenta$/);
  await expect(c.locator('.metric')).toContainText('10.000');
  await a.goto('http://127.0.0.1:5173/admin/historial');
  await expect(a.getByText(clientName)).toBeVisible();
  await a.getByLabel('Cliente identificado').fill(clientName);
  await a.getByRole('button',{name:'Buscar cliente'}).click();
  await a.getByRole('button',{name:new RegExp(clientName)}).click();
  await expect(a.getByText(`Cliente: ${clientName}`)).toBeVisible();
  await expect(a.getByRole('link').filter({hasText:clientName}).getByText('Transferencia')).toBeVisible();

  for (const [width,height] of [[320,568],[375,812],[390,844],[430,932],[768,1024],[1024,768],[1440,900],[1920,1080]]) {
    await a.setViewportSize({width,height});
    await c.setViewportSize({width,height});
    expect(await a.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),`admin horizontal overflow at ${width}`).toBe(true);
    expect(await c.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),`client horizontal overflow at ${width}`).toBe(true);
  }
  const revoked=await root.from('account_access').delete().eq('account_id',accountId);
  expect(revoked.error).toBeNull();
  await expect(c).toHaveURL(/\/vincular$/);
  await expect(c.getByText(clientName)).toHaveCount(0);
  await c.goto('http://127.0.0.1:5173/mi-cuenta');
  await expect(c).toHaveURL(/\/vincular$/);
  expect(errors).toEqual([]);
  await admin.close();await customer.close();await outsider.close();
});
